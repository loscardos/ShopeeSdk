using System.Text;

namespace Loscardos.ShopeeSdk.Generator;

public sealed class ManagersWriter
{
    public string WriteInterface(string moduleName, string moduleKey, IReadOnlyList<SchemaEndpoint> endpoints)
    {
        var modulePascal = ShopeeName.ToPascalCase(moduleKey);
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine($"using Loscardos.ShopeeSdk.Generated.{modulePascal};");
        builder.AppendLine();
        builder.AppendLine("namespace Loscardos.ShopeeSdk.Abstractions.Managers.Generated;");
        builder.AppendLine();
        builder.AppendLine($"public interface {ShopeeName.ToManagerInterfaceName(moduleKey)}");
        builder.AppendLine("{");

        foreach (var endpoint in endpoints.OrderBy(endpoint => endpoint.Path, StringComparer.Ordinal))
        {
            var requestType = ShopeeName.ToRequestTypeName(endpoint);
            var responseType = ShopeeName.ToResponseTypeName(endpoint);
            var methodName = ShopeeName.ToMethodName(endpoint.Path);
            var ownerParameter = endpoint.AuthScope switch
            {
                ShopeeSchemaAuthScope.Shop => "long shopId, ",
                ShopeeSchemaAuthScope.Merchant => "long merchantId, ",
                _ => string.Empty
            };
            builder.AppendLine($"    Task<{responseType}> {methodName}({ownerParameter}{requestType} request, CancellationToken cancellationToken);");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    public string WriteImplementation(string moduleName, string moduleKey, IReadOnlyList<SchemaEndpoint> endpoints)
    {
        var modulePascal = ShopeeName.ToPascalCase(moduleKey);
        var className = ShopeeName.ToManagerImplementationName(moduleKey);
        var interfaceName = ShopeeName.ToManagerInterfaceName(moduleKey);
        var needsTokenService = endpoints.Any(endpoint => endpoint.AuthScope != ShopeeSchemaAuthScope.Public);
        var constructorParameters = needsTokenService
            ? "IShopeeClient client, ShopeeTokenService tokenService"
            : "IShopeeClient client";
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using Loscardos.ShopeeSdk.Abstractions.Http;");
        builder.AppendLine("using Loscardos.ShopeeSdk.Abstractions.Managers.Generated;");
        if (needsTokenService)
        {
            builder.AppendLine("using Loscardos.ShopeeSdk.Core.Auth;");
        }

        builder.AppendLine($"using Loscardos.ShopeeSdk.Generated.{modulePascal};");
        builder.AppendLine();
        builder.AppendLine("namespace Loscardos.ShopeeSdk.Core.Managers.Generated;");
        builder.AppendLine();
        builder.AppendLine($"public sealed class {className}({constructorParameters}) : {interfaceName}");
        builder.AppendLine("{");

        foreach (var endpoint in endpoints.OrderBy(endpoint => endpoint.Path, StringComparer.Ordinal))
        {
            WriteMethod(builder, endpoint);
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void WriteMethod(StringBuilder builder, SchemaEndpoint endpoint)
    {
        var requestType = ShopeeName.ToRequestTypeName(endpoint);
        var responseType = ShopeeName.ToResponseTypeName(endpoint);
        var methodName = ShopeeName.ToMethodName(endpoint.Path);
        var ownerParameter = endpoint.AuthScope switch
        {
            ShopeeSchemaAuthScope.Shop => "long shopId, ",
            ShopeeSchemaAuthScope.Merchant => "long merchantId, ",
            _ => string.Empty
        };
        var authExpression = endpoint.AuthScope switch
        {
            ShopeeSchemaAuthScope.Shop => "new ShopeeRequestAuth(shopId, null)",
            ShopeeSchemaAuthScope.Merchant => "new ShopeeRequestAuth(null, merchantId)",
            _ => "null"
        };
        var method = endpoint.HttpMethod == ShopeeSchemaHttpMethod.Get ? "ShopeeRequestMethod.Get" : "ShopeeRequestMethod.Post";
        var bodyExpression = endpoint.RequestContentKind == ShopeeSchemaRequestContentKind.Query ? "null" : "request";
        var contentKind = endpoint.RequestContentKind == ShopeeSchemaRequestContentKind.Multipart
            ? ", ShopeeRequestContentKind.Multipart"
            : string.Empty;

        builder.AppendLine();
        builder.AppendLine($"    public async Task<{responseType}> {methodName}({ownerParameter}{requestType} request, CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine("        var query = new Dictionary<string, object?>();");

        if (endpoint.AuthScope == ShopeeSchemaAuthScope.Shop)
        {
            builder.AppendLine("        var token = await tokenService.GetValidTokenAsync(shopId, null, cancellationToken);");
            builder.AppendLine("        query[\"access_token\"] = token.AccessToken;");
        }
        else if (endpoint.AuthScope == ShopeeSchemaAuthScope.Merchant)
        {
            builder.AppendLine("        var token = await tokenService.GetValidTokenAsync(null, merchantId, cancellationToken);");
            builder.AppendLine("        query[\"access_token\"] = token.AccessToken;");
        }

        foreach (var parameter in endpoint.RequestParameters.Where(parameter => endpoint.RequestContentKind == ShopeeSchemaRequestContentKind.Query))
        {
            builder.AppendLine($"        query[\"{parameter.Name}\"] = request.{ShopeeName.ToPropertyName(parameter.Name)};");
        }

        builder.AppendLine($"        var envelope = await client.SendAsync<{responseType}>(");
        builder.AppendLine($"            new ShopeeRequest({method}, \"{endpoint.Path}\", query, {bodyExpression}, {authExpression}{contentKind}),");
        builder.AppendLine("            cancellationToken);");
        builder.AppendLine($"        return envelope.Response ?? new {responseType}();");
        builder.AppendLine("    }");
    }
}
